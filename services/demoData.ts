const DAY_MS = 24 * 60 * 60 * 1000;
const now = Date.now();
const ago = (days: number) => now - days * DAY_MS;
const ahead = (days: number) => now + days * DAY_MS;
const localDate = (date: Date): string => {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
};

const weekdays: (Weekday | null)[] = [
  null, 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday',
];

const recentClassDate = (daysAgo: number): Date => {
  const date = new Date(now - daysAgo * DAY_MS);
  while (date.getDay() === 0) date.setDate(date.getDate() - 1);
  return date;
};

